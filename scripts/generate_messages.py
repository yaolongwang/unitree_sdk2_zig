#!/usr/bin/env python3
"""从固定版本 SDK 的 IDL 头文件生成逐字段转换的 C/Zig DDS 绑定。

不导出 C++ 对象布局；解析器拒绝未知字段语法，防止上游新增字段被遗漏。
使用 --check 核对消息声明、转换代码和接口文档是否需要重新生成。
"""

from __future__ import annotations

import argparse
import dataclasses
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
SCALARS = {
    "bool": "uint8_t",
    "float": "float",
    "double": "double",
    **{f"{s}int{n}_t": f"{s}int{n}_t" for s in ("", "u") for n in (8, 16, 32, 64)},
}


@dataclasses.dataclass
class Message:
    group: str
    name: str
    cpp: str
    header: str
    fields: list[tuple[str, str]]
    type_id: int = 0

    @property
    def c(self) -> str:
        return f"usdk_{self.group}_{self.name}"

    @property
    def constant(self) -> str:
        return f"USDK_MESSAGE_{self.group}_{self.name}".upper()


def parse(upstream: pathlib.Path) -> list[Message]:
    include = upstream / "include"
    # Path ordering differs by OS; sort explicit POSIX strings for stable generation.
    paths = sorted((include / "unitree/idl").rglob("*.hpp"), key=lambda p: p.as_posix())
    paths += sorted(
        (include / "unitree/robot/internal/internal_idl_decl").glob("*.hpp"),
        key=lambda p: p.as_posix(),
    )
    messages = []
    for path in paths:
        source = path.read_text(encoding="utf-8")
        match = re.search(r"class\s+(\w+)\s*\{\s*private:(.*?)public:", source, re.S)
        if not match:
            raise ValueError(f"Cannot parse IDL class: {path}")
        type_name = re.search(r'getTypeName\(\)\s*\{\s*return\s+"([^"]+)"', source)
        if not type_name:
            raise ValueError(f"Missing DDS type name: {path}")
        cpp = "::" + type_name[1]
        group = path.parent.name if "internal_idl_decl" not in path.parts else "api"
        fields = []
        for declaration in match[2].split(";"):
            declaration = declaration.strip()
            if not declaration:
                continue
            field = re.fullmatch(r"(.+?)\s+(\w+)_\s*(?:=.*)?", declaration, re.S)
            if not field:
                raise ValueError(f"Unknown field: {path}: {declaration!r}")
            fields.append((re.sub(r"\s+", " ", field[1]), field[2]))
        messages.append(
            Message(
                group,
                match[1].removesuffix("_"),
                cpp,
                path.relative_to(include).as_posix(),
                fields,
            )
        )
    # IDs depend on sorted fully qualified names; the pinned manifest records them.
    for type_id, message in enumerate(sorted(messages, key=lambda m: m.cpp), 1):
        message.type_id = type_id
    return messages


def array(t: str):
    return re.fullmatch(r"std::array<(.+),\s*(\d+)>", t)


def vector(t: str):
    return re.fullmatch(r"std::vector<(.+)>", t)


def outputs(messages: list[Message]) -> dict[str, str]:
    by_cpp = {m.cpp: m for m in messages}

    def ctype(t: str) -> str:
        if t in SCALARS:
            return SCALARS[t]
        if t == "std::string":
            return "usdk_string"
        if t in by_cpp:
            return by_cpp[t].c
        if v := vector(t):
            return ctype(v[1]) + "_sequence"
        raise ValueError(f"Unknown IDL type {t}")

    ordered = []
    visited = set()

    def visit(m: Message):
        if m.cpp in visited:
            return
        visited.add(m.cpp)
        for t, _ in m.fields:
            child = array(t) or vector(t)
            if child:
                t = child[1]
            if t in by_cpp:
                visit(by_cpp[t])
        ordered.append(m)

    for m in messages:
        visit(m)
    head = [
        "/* Generated by scripts/generate_messages.py. Do not edit. */",
        "#ifndef USDK_MESSAGES_H",
        "#define USDK_MESSAGES_H",
        '#include "usdk.h"',
        "#ifdef __cplusplus",
        'extern "C" {',
        "#endif",
        "",
    ]
    sequences = set()
    for m in ordered:
        for t, _ in m.fields:
            if vector(t) and ctype(t) not in sequences:
                sequences.add(ctype(t))
                head.append(
                    f"typedef struct {{ const {ctype(vector(t)[1])} *data; size_t len; }} {ctype(t)};"
                )
        head.append(f"typedef struct {m.c} {{")
        for t, name in m.fields:
            if a := array(t):
                head.append(f"    {ctype(a[1])} {name}[{a[2]}];")
            else:
                head.append(f"    {ctype(t)} {name};")
        head.append(f"}} {m.c};\n")
    head.append("typedef enum usdk_message_type {")
    head += [
        f"    {m.constant} = {m.type_id},"
        for m in sorted(messages, key=lambda m: m.type_id)
    ]
    head += ["} usdk_message_type;", f"#define USDK_MESSAGE_COUNT {len(messages)}", ""]
    head += [
        "enum usdk_point_field_type {",
        "    USDK_POINT_FIELD_INT8 = 1, USDK_POINT_FIELD_UINT8 = 2,",
        "    USDK_POINT_FIELD_INT16 = 3, USDK_POINT_FIELD_UINT16 = 4,",
        "    USDK_POINT_FIELD_INT32 = 5, USDK_POINT_FIELD_UINT32 = 6,",
        "    USDK_POINT_FIELD_FLOAT32 = 7, USDK_POINT_FIELD_FLOAT64 = 8",
        "};",
        "",
    ]
    head += [HEADER_API, "#ifdef __cplusplus", "}", "#endif", "#endif", ""]

    zig = [
        "//! Generated, field-wise C views of every pinned SDK DDS message.",
        "//! Variable-length fields borrow storage; clone messages to retain callback data.",
        'const raw = @import("raw");',
        'const std = @import("std");',
        "pub const String = raw.usdk_string;",
        "",
    ]
    zig += [
        "pub const PointFieldType = enum(u8) {",
        "    int8 = 1,",
        "    uint8 = 2,",
        "    int16 = 3,",
        "    uint16 = 4,",
        "    int32 = 5,",
        "    uint32 = 6,",
        "    float32 = 7,",
        "    float64 = 8,",
        "};",
        "",
        "/// Construct a zero-initialized message, including padding and empty sequences.",
        "pub fn init(comptime T: type) T {",
        "    _ = typeId(T);",
        "    return std.mem.zeroes(T);",
        "}",
        "",
    ]
    for group in sorted({m.group for m in messages}):
        zig.append(f"pub const {group} = struct {{")
        for m in sorted(messages, key=lambda m: m.name):
            if m.group == group:
                zig.append(f"    pub const {m.name} = raw.{m.c};")
        zig.append("};\n")
    zig += [
        "/// Stable within the pinned upstream/schema version. Do not persist across regeneration.",
        "pub fn typeId(comptime T: type) u32 {",
        "    @setEvalBranchQuota(10000);",
    ]
    zig += [f"    if (T == {m.group}.{m.name}) return {m.type_id};" for m in messages]
    zig += [
        '    @compileError("T is not a Unitree SDK2 message type");',
        "}",
        f"pub const count: usize = {len(messages)};",
        "",
        'test "all generated message types have unique IDs and C layouts" {',
    ]
    zig += [
        f"    try std.testing.expectEqual(@as(u32, {m.type_id}), typeId({m.group}.{m.name}));"
        for m in messages
    ]
    zig += ["}", ""]

    main = [
        "// Generated by scripts/generate_messages.py. Do not edit.",
        '#include "messages_internal.hpp"',
        "",
    ]
    groups = sorted({m.group for m in messages})
    for group in groups:
        main.append(f"const MessageOps *message_ops_{group}(uint32_t id);")
    main += [
        "const MessageOps *message_ops(uint32_t id) {",
        "    const MessageOps *ops;",
    ]
    main += [f"    if ((ops = message_ops_{g}(id))) return ops;" for g in groups]
    main += [
        '    throw std::invalid_argument("unknown message type ID");',
        "}",
        NATIVE_API,
    ]

    out = {
        "include/usdk_messages.h": "\n".join(head),
        "src/messages.zig": "\n".join(zig),
        "src/cpp/generated/messages.cpp": "\n".join(main),
        "src/cpp/generated/messages_internal.hpp": INTERNAL,
    }
    for group in groups:
        group_messages = [m for m in ordered if m.group == group]
        code = [
            "// Generated by scripts/generate_messages.py. Do not edit.",
            '#include "messages_internal.hpp"',
        ]
        code += [f"#include <{m.header}>" for m in group_messages]
        code += ["namespace {", ""]
        for m in group_messages:
            code += [f"void from_view(const {m.c}& src, {m.cpp}& dst) {{"]
            for t, name in m.fields:
                code.append(f"    read_value(src.{name}, dst.{name}());")
            code += [
                "}",
                f"void to_view(const {m.cpp}& src, {m.c}& dst, MessageArena& arena) {{",
            ]
            for t, name in m.fields:
                code.append(f"    write_value(src.{name}(), dst.{name}, arena);")
            code += ["}", ""]
        # Overloads must be visible before templates instantiate via ADL; each
        # specialization provides explicit field conversion without ABI casts.
        code += [
            "}",
            f"const MessageOps *message_ops_{group}(uint32_t id) {{",
            "    switch (id) {",
        ]
        for m in group_messages:
            code += [
                f"    case {m.type_id}: {{",
                f'        static const MessageOps ops = make_ops<{m.cpp}, {m.c}, from_view, to_view>({m.type_id}, "{m.cpp.removeprefix("::")}");',
                "        return &ops;",
                "    }",
            ]
        code += ["    default: return nullptr;", "    }", "}", ""]
        # read_value/write_value templated aggregate overloads dispatch to these
        # definitions through ADL; definitions live at global scope, as C views do.
        code = [line for line in code if line != "namespace {"]
        close_index = (
            code.index(f"const MessageOps *message_ops_{group}(uint32_t id) {{") - 1
        )
        del code[close_index]
        out[f"src/cpp/generated/messages_{group}.cpp"] = "\n".join(code)
    rows = [
        "# DDS 消息与通道",
        "",
        "<!-- Generated by scripts/generate_messages.py; do not edit. -->",
        "",
        "`sdk.messages` 提供 72 种消息类型。每种类型均可用于 `sdk.Publisher(T)`、`sdk.Subscriber(T)` 和 `sdk.Message(T)`。",
        "",
        "使用 `sdk.messages.init(T)` 创建零初始化消息。回调中的消息是借用视图；需要保留时，调用 `sdk.Message(T).clone(message)` 深拷贝，并在使用后调用 `deinit()`。",
        "",
        "| ID | Zig 类型 | DDS 类型 |",
        "| --- | --- | --- |",
    ]
    rows += [
        f"| {m.type_id} | `messages.{m.group}.{m.name}` | `{m.cpp.removeprefix('::')}` |"
        for m in sorted(messages, key=lambda m: m.type_id)
    ]
    rows += [
        "",
        "频道初始化由 `ChannelFactory.init` 完成。`Publisher(T)` 只接受相同消息类型。字符串和变长序列使用 `data` + `len`，长度为零时允许空指针。消息字符串允许内嵌 NUL；topic 必须是 NUL 结尾字符串。",
        "",
        "订阅回调运行于 SDK 线程，传入的整个视图（含嵌套指针）仅在该次回调期间有效。需要保留时调用 `Message(T).clone`，并在使用结束后 `deinit`。回调内不可销毁自己的订阅；从拥有该订阅的线程销毁。关闭订阅前应确保没有业务代码仍访问 borrowed view。不同线程并发调用同一 handle 或 close/write 必须由调用方同步。",
        "",
        "`lastDataTime` 返回最近消息进入桥接回调时的单调时钟纳秒数，尚未收到数据时为 0；桥接使用原子存储，避免并发读取上游非原子时间字段。写入的 `wait_us` 是上游匹配订阅端的等待时间。订阅回调发生转换失败时捕获异常；`checkLastCallback` 可以读取最近一次回调的状态。用户回调不能跨 C ABI 抛异常。",
        "",
        "生成器使用 `--check` 比较所有生成文件；改变固定上游后必须审查 ID、字段与 ABI 的变化。",
        "",
    ]
    out["docs/messages.md"] = "\n".join(rows)
    return out


